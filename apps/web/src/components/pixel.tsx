export type PixelName = keyof typeof ICONS;

export function PixelIcon({ name, scale = 2 }: { name: PixelName; scale?: number }) {
  const path = ICONS[name].flatMap((row, y) => [...row].map((cell, x) => (cell === "#" ? `M${x} ${y}h1v1h-1z` : ""))).join("");
  return (
    <svg width={8 * scale} height={8 * scale} viewBox="0 0 8 8" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true" className="shrink-0">
      <path d={path} />
    </svg>
  );
}
